"use strict";

// Decodes the committed offline fixtures through the public entry points and
// checks the results against a reference decoder written independently of
// lib/. Also verifies the committed bytes still match the generator's output,
// so a fixture that silently drifts (or is replaced by a truncated file)
// fails loudly instead of weakening the suite.

let test = require("tape");
let fs = require("fs");
let path = require("path");

let PNG = require("../lib/png").PNG;
let builder = require("./fixtures/png-builder");
let definitions = require("./fixtures/definitions");
let manifest = require("./fixtures/manifest.json");

let FIXTURE_DIR = path.join(__dirname, "fixtures");

function load(name) {
  return fs.readFileSync(path.join(FIXTURE_DIR, name));
}

let names = Object.keys(definitions);

test("offline fixtures: manifest covers every fixture", function (t) {
  t.deepEqual(
    Object.keys(manifest).sort(),
    names.slice().sort(),
    "manifest lists exactly the generated fixtures"
  );
  t.end();
});

test("offline fixtures: files present and generated bytes are reproducible", function (t) {
  names.forEach(function (name) {
    let onDisk;
    try {
      onDisk = load(name);
    } catch (err) {
      t.fail(name + ": missing (" + err.message + ")");
      return;
    }
    t.ok(onDisk.length > 0, name + ": non-empty");
    let regenerated = builder.build(definitions[name]);
    t.ok(
      Buffer.compare(onDisk, regenerated) === 0,
      name + ": committed bytes match the spec-derived generator"
    );
  });
  t.end();
});

test("offline fixtures: every fixture decodes to the reference pixels", function (t) {
  names.forEach(function (name) {
    let opts = definitions[name];
    let expected = builder.expectedRgba(opts);
    let parsed;
    try {
      parsed = PNG.sync.read(load(name));
    } catch (err) {
      t.fail(name + ": failed to decode: " + err.code + " " + err.message);
      return;
    }
    t.equal(parsed.width, opts.width, name + ": width");
    t.equal(parsed.height, opts.height, name + ": height");
    t.equal(parsed.depth, opts.depth, name + ": depth");
    t.ok(
      Buffer.compare(parsed.data, expected) === 0,
      name + ": pixels match the reference"
    );
  });
  t.end();
});

test("offline fixtures: palette and transparency metadata", function (t) {
  let indexed = PNG.sync.read(load("indexed8-trns.png"));
  t.equal(indexed.colorType, 3, "indexed8-trns: colour type");
  t.ok(Array.isArray(indexed.palette), "indexed8-trns: palette exposed");
  t.deepEqual(
    indexed.palette.map(function (entry) {
      return entry[3];
    }),
    [0, 64, 128, 255, 255],
    "indexed8-trns: tRNS alpha values"
  );

  let grayKey = PNG.sync.read(load("gray8-trns.png"));
  t.deepEqual(grayKey.transColor, [128], "gray8-trns: colour key exposed");
  t.equal(grayKey.alpha, true, "gray8-trns: alpha flag");

  let rgbKey = PNG.sync.read(load("rgb8-trns.png"));
  t.deepEqual(rgbKey.transColor, [16, 32, 48], "rgb8-trns: colour key exposed");

  let gamma = PNG.sync.read(load("gray8-gamma.png"));
  t.equal(gamma.gamma, 0.45455, "gray8-gamma: gamma decoded");
  t.end();
});

test("offline fixtures: interlaced and plain agree pixel for pixel", function (t) {
  [
    "rgba8-interlaced.png",
    "gray16-interlaced.png",
    "indexed1-interlaced.png",
  ].forEach(function (name) {
    let opts = Object.assign({}, definitions[name], { interlace: false });
    let expected = PNG.sync.read(builder.build(opts)).data;
    let actual = PNG.sync.read(load(name)).data;
    t.ok(Buffer.compare(actual, expected) === 0, name + ": same pixels");
  });
  t.end();
});

test("offline fixtures: split IDAT chunks decode identically to a single chunk", function (t) {
  let opts = Object.assign({}, definitions["rgba8-split-idat.png"], {
    idatSplit: 0,
  });
  t.ok(
    Buffer.compare(
      PNG.sync.read(load("rgba8-split-idat.png")).data,
      PNG.sync.read(builder.build(opts)).data
    ) === 0,
    "split IDAT: same pixels"
  );
  t.end();
});

test("offline fixtures: stream decoding matches buffer decoding byte for byte", function (t) {
  let pending = [];
  names.forEach(function (name) {
    let buffer = load(name);
    let sync = PNG.sync.read(buffer);
    pending.push(
      new Promise(function (resolve) {
        let png = new PNG();
        png.on("parsed", function () {
          t.ok(
            Buffer.compare(png.data, sync.data) === 0,
            name + ": stream pixels match buffer pixels"
          );
          resolve();
        });
        png.on("error", function (err) {
          t.fail(name + ": stream error " + (err.code || err.message));
          resolve();
        });
        // Feed one byte at a time: every split point is exercised.
        for (let i = 0; i < buffer.length; i++) {
          png.write(buffer.slice(i, i + 1));
        }
        png.end();
      })
    );
  });
  return Promise.all(pending).then(function () {
    t.end();
  });
});
